function translateTerms(value) {
  if (koPhrases[value]) return koPhrases[value];
  if (value.startsWith('controlled-')) return `부모가 관리하는 ${translateTerms(value.slice('controlled-'.length))}`;
  if (value.endsWith('-policy')) return `${translateTerms(value.slice(0, -'-policy'.length))} 규칙`;
  return value
    .split('-')
    .map((term) => term === 'and' ? '및' : term === 'or' ? '또는' : (koTerms[term] ?? term))
    .join(' ');
}

function koDescription(component) {
  const exact = koComponentSummaries[component.id];
  assert.equal(typeof exact, 'string', `Missing Korean component summary: ${component.id}`);
  return exact;
}

