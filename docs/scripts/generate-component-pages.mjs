function page(component) {
  const name = title(component.id);
  const capabilities = component.capabilities.map((value) => `- ${sentence(value)}.`).join('\n');
  const standard = component.standard.startsWith('http') ? component.standard : theoryLink(component.family);
  const scenarios = [...new Set([...component.scenarios.dom, ...component.scenarios.terminal])]
    .map((value) => `### ${sentence(value)}\n\nUse this case to inspect ${value.replaceAll('-', ' ')} independently from the component's other behavior.`)
    .join('\n\n');
  return `<!-- Generated by scripts/generate-component-pages.mjs. -->
# ${name}

${description(component.family, name)}

## Basic usage

Import the public subpath for the selected environment. The environment selector in the site header applies to every code example.

<PackageImport component="${component.id}" />

## Features

${capabilities}

Each feature is part of the public semantic contract. Host packages may expose different input and rendering helpers while preserving accepted transitions.

## Example cases

${scenarios}

## State ownership

State that changes application-owned data supports controlled or uncontrolled ownership where the component contract permits it. Use uncontrolled state for local behavior and controlled state when a parent coordinates validation, persistence, or multiple controls.

## Disabled and readonly

Host projections distinguish disabled interaction from readonly inspection when the underlying control permits both. Disabled controls leave the interaction sequence; readonly controls remain available for inspection while rejecting mutation.

## Package availability

| Package | Import | Status |
| --- | --- | --- |
| Core | \`@sectile/core/${component.id}\` | Published |
| DOM | \`@sectile/dom/${component.id}\` | Published |
| Terminal | \`@sectile/terminal/${component.id}\` | Published |
| Vue | \`@sectile/vue/${component.id}\` | Workspace preview |

## Semantics

The component contract follows [${standard.startsWith('http') ? 'the relevant accessibility pattern' : 'Sectile composition theory'}](${standard}). Visual styling remains outside the package; use host attributes, parts, and state projections as styling hooks.
`;
}

