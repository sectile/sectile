function scenarioSection(component, scenarios, korean = false, startIndex = 0) {
  return scenarios
    .map((value, offset) => {
      const scenarioName = korean ? koScenarioTitle(component, value) : scenarioTitle(component, value);
      const scenarioCopy = korean ? koScenarioDescription(component, value) : scenarioDescription(component, value);
      return `### ${scenarioName}\n\n${scenarioCopy}\n\n<ComponentExample component="${component.id}" scenario="${value}" title="${scenarioName}" description="${scenarioCopy}" :index="${startIndex + offset}" />`;
    })
    .join('\n\n');
}

function optionalExamplesSection(component, scenarios, startIndex, korean = false) {
  if (scenarios.length === 0) return '';
  const heading = korean ? '## 예시' : '## Examples';
  return `\n\n${heading}\n\n${scenarioSection(component, scenarios, korean, startIndex)}`;
}

