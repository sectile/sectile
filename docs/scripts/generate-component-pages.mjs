function apiSection(component, korean = false) {
  const {
    values,
    types,
    functions,
    componentEvents,
    contracts,
    defaults,
    functionSignatures,
    typeDefinitions,
  } = publicVueApi(component.id);
  const functionSet = new Set(functions);
  const components = values.filter((value) => !functionSet.has(value));
  const hiddenTypes = types.filter((value) => value.endsWith('PublicProps'));
  const propTypes = types.filter((value) => (
    value.endsWith('Props')
    && !value.endsWith('SlotProps')
    && !value.endsWith('PublicProps')
  ));
  const slotTypes = types.filter((value) => value.endsWith('SlotProps'));
  const eventTypes = types.filter((value) => /(?:Event|Emits)$/u.test(value));
  const classified = new Set([...hiddenTypes, ...propTypes, ...slotTypes, ...eventTypes]);
  const otherTypes = types.filter((value) => !classified.has(value));
  const tokenList = (values, kind) => `<div class="component-api-group">
<strong class="component-api-label">${kind}</strong>
<ul class="component-api-list">
${values.map((value) => `  <li><code class="component-api-token">${value}</code></li>`).join('\n')}
</ul>
</div>`;
  const heading = '## API';
  const introduction = korean
    ? `Vue 패키지: \`@sectile/vue/${component.id}\``
    : `Vue package: \`@sectile/vue/${component.id}\``;
  const groups = [
    tokenList(components, korean ? '컴포넌트' : 'Components'),
    apiFunctionGroup(functions, functionSignatures, korean),
    apiContractGroup(component.id, propTypes, contracts, defaults, 'props', 'Props', korean),
    apiContractGroup(component.id, slotTypes, contracts, defaults, 'slots', korean ? '슬롯' : 'Slots', korean),
    apiComponentEventGroup(componentEvents, korean),
    apiTypeGroup(eventTypes, contracts, typeDefinitions, korean ? '이벤트' : 'Events', korean),
    apiTypeGroup(otherTypes, contracts, typeDefinitions, korean ? '기타 타입' : 'Other types', korean),
  ].filter(Boolean).join('\n\n');
  return `${heading}\n\n${introduction}\n\n${groups}`;
}

function apiComponentEventGroup(componentEvents, korean) {
  const entries = Object.entries(componentEvents).filter(([, events]) => events.length > 0);
  if (entries.length === 0) return undefined;
  const heading = korean ? '이벤트' : 'Events';
  const labels = korean ? ['이벤트', '페이로드', '설명'] : ['Event', 'Payload', 'Description'];
  return `### ${heading}\n\n${entries.map(([name, events]) => {
    const rows = sortApiProperties(events, 'events').map((event) => {
      const payload = event.payload === '—' ? '—' : htmlCode(event.payload);
      const description = vueApiDescription(korean ? 'ko' : 'en', 'events', event.name);
      return { cells: [htmlCode(event.name), payload], description: escapeHtml(description) };
    });
    return `#### ${inlineCode(name)}\n\n${apiDefinitionList('events', labels, rows)}`;
  }).join('\n\n')}`;
}

function apiFunctionGroup(names, signatures, korean) {
  if (names.length === 0) return undefined;
  const heading = korean ? '함수' : 'Functions';
  return `### ${heading}\n\n${names.map((name) => `#### \`${name}\`\n\n\`\`\`ts\n${signatures[name]}\n\`\`\``).join('\n\n')}`;
}

function apiTypeGroup(names, contracts, definitions, heading, korean) {
  if (names.length === 0) return undefined;
  const entries = names.map((name) => {
    const properties = contracts[name] ?? [];
    if (properties.length === 0) {
      const definition = definitions[name];
      return definition === undefined
        ? `#### \`${name}\``
        : `#### \`${name}\`\n\n\`\`\`ts\n${definition}\n\`\`\``;
    }
    const labels = korean ? ['이름', '타입', '필수'] : ['Name', 'Type', 'Required'];
    const rows = properties.map((property) => `| \`${property.name}\` | \`${property.type.replaceAll('|', '\\|')}\` | ${property.optional ? '—' : korean ? '필수' : 'Yes'} |`).join('\n');
    return `#### \`${name}\`\n\n| ${labels.join(' | ')} |\n| --- | --- | --- |\n${rows}`;
  }).join('\n\n');
  return `### ${heading}\n\n${entries}`;
}

function apiContractGroup(component, names, contracts, defaults, kind, heading, korean) {
  if (names.length === 0) return undefined;
  const locale = korean ? 'ko' : 'en';
  const entries = names.map((name) => {
    const properties = contracts[name] ?? [];
    assert.ok(properties.length > 0, `${name} requires a documented ${kind} contract`);
    const labels = kind === 'props'
      ? korean ? ['속성', '타입', '기본값', '설명'] : ['Prop', 'Type', 'Default', 'Description']
      : korean ? ['값', '타입', '설명'] : ['Value', 'Type', 'Description'];
    const rows = sortApiProperties(properties, kind).map((property) => {
      const cells = [htmlCode(property.name), htmlCode(property.type)];
      if (kind === 'props') {
        if (!property.optional) {
          cells.push(korean ? '필수' : 'Required');
        } else {
          const defaultValue = vueApiDefault(locale, component, name, property.name, defaults[name]?.[property.name]);
          cells.push(defaultValue.code === undefined ? escapeHtml(defaultValue.text) : htmlCode(defaultValue.code));
        }
      }
      return {
        cells,
        description: escapeHtml(vueApiDescription(locale, kind, property.name, component)),
      };
    });
    return `#### ${inlineCode(name)}\n\n${apiDefinitionList(kind, labels, rows)}`;
  }).join('\n\n');
  return `### ${heading}\n\n${entries}`;
}

function sortApiProperties(properties) {
  return [...properties].sort((left, right) => left.name.localeCompare(right.name, 'en', {
    numeric: true,
    sensitivity: 'base',
  }));
}

function inlineCode(value) {
  return `\`${value}\``;
}

function htmlCode(value) {
  return `<code>${escapeHtml(value)}</code>`;
}

function apiDefinitionList(kind, labels, rows) {
  const metadataLabels = labels.slice(1, -1);
  return `<dl class="component-api-definitions component-api-definitions--${kind}">
${rows.map((row) => `<div class="component-api-definition">
<dt>${row.cells[0]}</dt>
<dd>
<div class="component-api-definition__metadata">${row.cells.slice(1).map((cell, index) => `<span><span class="component-api-definition__label">${escapeHtml(metadataLabels[index])}</span>${cell}</span>`).join('')}</div>
<p>${row.description}</p>
</dd>
</div>`).join('\n')}
</dl>`;
}

function partsSection(component, korean = false) {
  const definition = componentAnatomy[component.id];
  assert.ok(definition, `Missing anatomy definition: ${component.id}`);
  const renderedParts = definition.parts.filter((part) => part !== 'provider');
  const rows = renderedParts.map((part) => {
    const contract = anatomyPartContract(definition, part);
    const scope = contract.attributes.find(([name]) => name === 'data-scope')?.[1] ?? definition.scope;
    const additionalAttributes = contract.attributes.filter(([name]) => !['data-scope', 'data-part'].includes(name));
    const exceptionalScope = scope === definition.scope
      ? []
      : [['data-scope', scope]];
    const extras = [...exceptionalScope, ...additionalAttributes];
    const extraCell = extras.length === 0
      ? '<span aria-label="None">—</span>'
      : extras.map(([name, value]) => `<code>${escapeHtml(name)}="${escapeHtml(value)}"</code>`).join('<br>');

    return `<tr>
  <td><code class="component-part-token">${escapeHtml(part)}</code></td>
  <td><code>[data-part="${escapeHtml(part)}"]</code></td>
  <td>${escapeHtml(contract.purpose[korean ? 'ko' : 'en'])}</td>
  <td>${extraCell}</td>
</tr>`;
  }).join('\n');
  const heading = korean ? '## 파트' : '## Parts';
  const introduction = korean
    ? `공통 범위: <code class="component-scope-token">[data-scope="${escapeHtml(definition.scope)}"]</code>. 컴포넌트 내부로 스타일을 제한할 때 파트 선택자와 함께 사용합니다.`
    : `Shared scope: <code class="component-scope-token">[data-scope="${escapeHtml(definition.scope)}"]</code>. Combine it with a part selector to keep styles local to this component.`;
  const headings = korean
    ? ['파트', '선택자', '역할', '추가 속성']
    : ['Part', 'Selector', 'Role', 'Extra attributes'];
  return `${heading}\n\n${introduction}\n\n<div class="component-parts-table">\n<table>\n<thead>\n<tr>${headings.map((label) => `<th scope="col">${label}</th>`).join('')}</tr>\n</thead>\n<tbody>\n${rows}\n</tbody>\n</table>\n</div>`;
}

function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

