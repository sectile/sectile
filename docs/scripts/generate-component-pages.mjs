function publicVueApi(component) {
  const sourceFile = vueSourceFiles[component];
  assert.ok(sourceFile, `Missing @sectile/vue source module: ${component}`);
  const moduleSymbol = vueChecker.getSymbolAtLocation(sourceFile);
  assert.ok(moduleSymbol, `Missing @sectile/vue module symbol: ${component}`);
  const exportedSymbols = vueChecker.getExportsOfModule(moduleSymbol);
  const values = [];
  const types = [];
  const functions = [];
  const componentEvents = {};
  const contracts = {};
  const defaults = componentPropDefaults(sourceFile);
  const functionSignatures = {};
  const typeDefinitions = {};

  for (const exportedSymbol of exportedSymbols) {
    const name = exportedSymbol.name;
    const symbol = exportedSymbol.flags & ts.SymbolFlags.Alias
      ? vueChecker.getAliasedSymbol(exportedSymbol)
      : exportedSymbol;
    const declarations = symbol.declarations ?? [];
    const isValue = (symbol.flags & ts.SymbolFlags.Value) !== 0;
    const isType = (symbol.flags & ts.SymbolFlags.Type) !== 0;

    if (isValue) {
      values.push(name);
      const declaration = symbol.valueDeclaration ?? declarations[0];
      if (declaration !== undefined && ts.isFunctionDeclaration(declaration)) {
        functions.push(name);
        functionSignatures[name] = functionSignature(name, declaration);
      } else if (declaration !== undefined) {
        componentEvents[name] = componentEventContracts(symbol, declaration);
      }
    }

    if (isType) {
      types.push(name);
      const publicType = vueChecker.getDeclaredTypeOfSymbol(
        exportedSymbol.flags & ts.SymbolFlags.Alias ? symbol : exportedSymbol,
      );
      const resolveContractPropertyTypes = component === 'form';
      const exposesProperties = name.endsWith('Props')
        || declarations.some(ts.isInterfaceDeclaration);
      contracts[name] = exposesProperties
        ? vueChecker.getPropertiesOfType(publicType).map((property) => {
            const declaration = property.valueDeclaration ?? property.declarations?.[0];
            const resolvedPropertyType = vueChecker.getTypeOfPropertyOfType(publicType, property.name);
            const type = resolveContractPropertyTypes && resolvedPropertyType !== undefined
              ? vueChecker.typeToString(
                  resolvedPropertyType,
                  declaration,
                  ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope,
                )
              : declaration !== undefined && 'type' in declaration && declaration.type !== undefined
              ? declaration.type.getText(declaration.getSourceFile())
              : declaration === undefined
                ? 'unknown'
                : vueChecker.typeToString(
                    vueChecker.getTypeOfSymbolAtLocation(property, declaration),
                    declaration,
                    ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope,
                  );
            return {
              name: property.name,
              type,
              optional: (property.flags & ts.SymbolFlags.Optional) !== 0,
            };
          })
        : [];
      const declaration = declarations.find(ts.isTypeAliasDeclaration);
      if (declaration !== undefined) {
        const parameters = declaration.typeParameters === undefined
          ? ''
          : `<${declaration.typeParameters.map((parameter) => parameter.getText(declaration.getSourceFile())).join(', ')}>`;
        const body = declaration.type.getText(declaration.getSourceFile());
        const separator = body.includes('\n') || /^[|&]/u.test(body) ? '\n' : ' ';
        typeDefinitions[name] = `type ${name}${parameters} =${separator}${body}`;
      } else if (contracts[name].length === 0) {
        const interfaceDeclaration = declarations.find(ts.isInterfaceDeclaration);
        if (interfaceDeclaration !== undefined) {
          typeDefinitions[name] = interfaceDeclaration
            .getText(interfaceDeclaration.getSourceFile())
            .replace(/^export\s+/u, '');
        }
      }
    }
  }
  assert.ok(values.length > 0, `${component} requires a public Vue value export`);
  assert.ok(types.length > 0, `${component} requires a public Vue type export`);
  return { values, types, functions, componentEvents, contracts, defaults, functionSignatures, typeDefinitions };
}

function publicDomFormApi() {
  const moduleSymbol = domChecker.getSymbolAtLocation(domFormSourceFile);
  assert.ok(moduleSymbol, 'Missing @sectile/dom form module symbol');
  const values = [];
  const types = [];
  const functions = [];
  const contracts = {};
  const functionSignatures = {};
  const typeDefinitions = {};

  for (const exportedSymbol of domChecker.getExportsOfModule(moduleSymbol)) {
    const name = exportedSymbol.name;
    const symbol = exportedSymbol.flags & ts.SymbolFlags.Alias
      ? domChecker.getAliasedSymbol(exportedSymbol)
      : exportedSymbol;
    const declarations = symbol.declarations ?? [];
    const isValue = (symbol.flags & ts.SymbolFlags.Value) !== 0;
    const isType = (symbol.flags & ts.SymbolFlags.Type) !== 0;

    if (isValue) {
      values.push(name);
      const functionDeclarations = declarations.filter(ts.isFunctionDeclaration);
      if (functionDeclarations.length > 0) {
        functions.push(name);
        const overloads = functionDeclarations.filter((declaration) => declaration.body === undefined);
        const signatures = overloads.length > 0 ? overloads : [functionDeclarations[0]];
        functionSignatures[name] = [...new Set(signatures.map((declaration) => functionSignature(name, declaration)))].join('\n');
      }
    }

    if (isType) {
      types.push(name);
      const publicType = domChecker.getDeclaredTypeOfSymbol(
        exportedSymbol.flags & ts.SymbolFlags.Alias ? symbol : exportedSymbol,
      );
      const exposesProperties = declarations.some(ts.isInterfaceDeclaration);
      contracts[name] = exposesProperties
        ? domChecker.getPropertiesOfType(publicType).map((property) => {
            const declaration = property.valueDeclaration ?? property.declarations?.[0];
            return {
              name: property.name,
              type: declaration === undefined
                ? 'unknown'
                : domChecker.typeToString(
                    domChecker.getTypeOfSymbolAtLocation(property, declaration),
                    declaration,
                    ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope,
                  ),
              optional: (property.flags & ts.SymbolFlags.Optional) !== 0,
            };
          })
        : [];
      const declaration = declarations.find(ts.isTypeAliasDeclaration);
      if (declaration !== undefined) {
        const parameters = declaration.typeParameters === undefined
          ? ''
          : `<${declaration.typeParameters.map((parameter) => parameter.getText(declaration.getSourceFile())).join(', ')}>`;
        const body = declaration.type.getText(declaration.getSourceFile());
        const separator = body.includes('\n') || /^[|&]/u.test(body) ? '\n' : ' ';
        typeDefinitions[name] = `type ${name}${parameters} =${separator}${body}`;
      }
    }
  }

  return { values, types, functions, contracts, functionSignatures, typeDefinitions };
}

function componentPropDefaults(sourceFile) {
  const defaults = {};
  for (const statement of sourceFile.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name) || declaration.initializer === undefined) continue;
      const options = defineComponentOptions(declaration.initializer);
      if (options === undefined || !ts.isObjectLiteralExpression(options)) continue;
      const props = objectPropertyInitializer(options, 'props');
      if (props === undefined || !ts.isObjectLiteralExpression(props)) continue;
      const typeName = `${declaration.name.text}Props`;
      const values = {};
      for (const property of props.properties) {
        if (!ts.isPropertyAssignment(property)) continue;
        const name = propertyName(property.name);
        if (name === undefined) continue;
        const option = unwrapExpression(property.initializer);
        if (ts.isObjectLiteralExpression(option)) {
          const defaultValue = objectPropertyInitializer(option, 'default');
          if (defaultValue !== undefined) values[name] = formatDefaultValue(defaultValue);
          continue;
        }
        if (ts.isIdentifier(option) && option.text === 'Boolean') values[name] = 'false';
      }
      defaults[typeName] = Object.freeze(values);
    }
  }
  return Object.freeze(defaults);
}

function defineComponentOptions(expression) {
  const value = unwrapExpression(expression);
  if (!ts.isCallExpression(value)) return undefined;
  const callee = unwrapExpression(value.expression);
  if (!ts.isIdentifier(callee) || callee.text !== 'defineComponent') return undefined;
  const options = value.arguments[0];
  return options === undefined ? undefined : unwrapExpression(options);
}

function objectPropertyInitializer(object, name) {
  for (const property of object.properties) {
    if (!ts.isPropertyAssignment(property)) continue;
    if (propertyName(property.name) === name) return unwrapExpression(property.initializer);
  }
  return undefined;
}

function propertyName(name) {
  if (ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isNumericLiteral(name)) return name.text;
  return undefined;
}

function unwrapExpression(expression) {
  let current = expression;
  while (
    ts.isAsExpression(current)
    || ts.isTypeAssertionExpression(current)
    || ts.isParenthesizedExpression(current)
    || ts.isSatisfiesExpression(current)
  ) current = current.expression;
  return current;
}

function formatDefaultValue(expression) {
  const value = unwrapExpression(expression);
  if (ts.isIdentifier(value) && value.text === 'undefined') return 'undefined';
  if (ts.isPropertyAccessExpression(value) && value.getText() === 'Number.POSITIVE_INFINITY') return 'Infinity';
  if (ts.isArrowFunction(value)) {
    const body = unwrapExpression(value.body);
    return body.getText(body.getSourceFile());
  }
  return value.getText(value.getSourceFile());
}

function componentEventContracts(symbol, declaration) {
  const componentType = vueChecker.getTypeOfSymbolAtLocation(symbol, declaration);
  const constructor = componentType.getConstructSignatures()[0];
  if (constructor === undefined) return [];
  const instance = constructor.getReturnType();
  const emit = instance.getProperty('$emit');
  const emitDeclaration = emit?.valueDeclaration ?? emit?.declarations?.[0];
  if (emit === undefined || emitDeclaration === undefined) return [];
  const emitType = vueChecker.getTypeOfSymbolAtLocation(emit, emitDeclaration);
  const flags = ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope;
  return emitType.getCallSignatures()
    .filter((signature) => {
      const event = signature.parameters[0];
      const eventDeclaration = event?.valueDeclaration ?? event?.declarations?.[0];
      if (event === undefined || eventDeclaration === undefined) return false;
      const eventType = vueChecker.getTypeOfSymbolAtLocation(event, eventDeclaration);
      return isEventNameType(eventType);
    })
    .flatMap((signature) => {
      const event = signature.parameters[0];
      const eventDeclaration = event.valueDeclaration ?? event.declarations?.[0];
      assert.ok(eventDeclaration);
      const eventType = vueChecker.getTypeOfSymbolAtLocation(event, eventDeclaration);
      const payloadParameters = signature.parameters.slice(1);
      const payloadTypes = payloadParameters.flatMap((parameter) => {
        const parameterDeclaration = parameter.valueDeclaration ?? parameter.declarations?.[0];
        assert.ok(parameterDeclaration);
        const parameterType = vueChecker.getTypeOfSymbolAtLocation(parameter, parameterDeclaration);
        const types = vueChecker.isTupleType(parameterType)
          ? vueChecker.getTypeArguments(parameterType)
          : [parameterType];
        return types.map((type) => vueChecker.typeToString(type, parameterDeclaration, flags));
      });
      const payload = payloadTypes.length === 0 ? '—' : payloadTypes.join(', ');
      return eventNames(eventType).map((name) => ({ name, payload }));
    });
}

function isEventNameType(type) {
  if ((type.flags & ts.TypeFlags.StringLiteral) !== 0) return true;
  return type.isUnion() && type.types.every((member) => (
    (member.flags & ts.TypeFlags.StringLiteral) !== 0
  ));
}

function eventNames(type) {
  if ((type.flags & ts.TypeFlags.StringLiteral) !== 0) return [type.value];
  assert.ok(type.isUnion());
  return type.types.map((member) => member.value);
}

function functionSignature(name, declaration) {
  const sourceFile = declaration.getSourceFile();
  const typeParameters = declaration.typeParameters === undefined
    ? ''
    : `<${declaration.typeParameters.map((parameter) => parameter.getText(sourceFile)).join(', ')}>`;
  const parameters = declaration.parameters.map((parameter) => parameter.getText(sourceFile)).join(', ');
  const returnType = declaration.type?.getText(sourceFile) ?? 'void';
  return `function ${name}${typeParameters}(${parameters}): ${returnType}`;
}

