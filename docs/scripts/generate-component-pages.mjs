function page(component) {
  const name = title(component.id);
  const examples = documentedScenarios(component);
  assert.ok(examples.length > 0, `${component.id}: requires at least one documented DOM example`);
  const scenarios = examples
    .map((value, index) => `### ${scenarioTitle(component, value)}\n\n${scenarioDescription(component, value)}\n\n<ComponentExample component="${component.id}" scenario="${value}" title="${scenarioTitle(component, value)}" description="${scenarioDescription(component, value)}" :index="${index}" />`)
    .join('\n\n');
  return `<!-- Generated by scripts/generate-component-pages.mjs. -->
# ${name}

${description(component)}

## Examples

${scenarios}

${apiSection(component)}

${partsSection(component)}

${keyboardSection(component)}

${accessibilitySection(component)}
`;
}

function pageKo(component) {
  const name = koComponentNames[component.id] ?? title(component.id);
  const examples = documentedScenarios(component);
  assert.ok(examples.length > 0, `${component.id}: requires at least one documented DOM example`);
  const scenarios = examples
    .map((value, index) => `### ${koScenarioTitle(component, value)}\n\n${koScenarioDescription(component, value)}\n\n<ComponentExample component="${component.id}" scenario="${value}" title="${koScenarioTitle(component, value)}" description="${koScenarioDescription(component, value)}" :index="${index}" />`)
    .join('\n\n');
  return `<!-- scripts/generate-component-pages.mjs에서 생성함. -->
# ${name}

${koDescription(component)}

## 예시

${scenarios}

${apiSection(component, true)}

${partsSection(component, true)}

${keyboardSection(component, true)}

${accessibilitySection(component, true)}
`;
}

function apiSection(component, korean = false) {
  const { values, types } = publicVueApi(component.id);
  const components = values.filter((value) => !value.startsWith('create'));
  const functions = values.filter((value) => value.startsWith('create'));
  const tokenList = (values, kind) => `<div class="component-api-group">
<strong class="component-api-label">${kind}</strong>
<ul class="component-api-list">
${values.map((value) => `  <li><code class="component-api-token">${value}</code></li>`).join('\n')}
</ul>
</div>`;
  const heading = korean ? '## 공개 API' : '## API reference';
  const introduction = korean
    ? `Vue 패키지: \`@sectile/vue/${component.id}\``
    : `Vue package: \`@sectile/vue/${component.id}\``;
  const groups = [
    tokenList(components, korean ? '컴포넌트' : 'Components'),
    functions.length === 0 ? undefined : tokenList(functions, korean ? '함수' : 'Functions'),
    tokenList(types, korean ? '타입' : 'Types'),
  ].filter(Boolean).join('\n\n');
  return `${heading}\n\n${introduction}\n\n${groups}`;
}

function partsSection(component, korean = false) {
  const definition = componentAnatomy[component.id];
  assert.ok(definition, `Missing anatomy definition: ${component.id}`);
  const renderedParts = definition.parts.filter((part) => part !== 'provider');
  const rows = renderedParts.map((part) => {
    const contract = anatomyPartContract(definition, part);
    const scope = contract.attributes.find(([name]) => name === 'data-scope')?.[1] ?? definition.scope;
    const additionalAttributes = contract.attributes.filter(([name]) => !['data-scope', 'data-part'].includes(name));
    const exceptionalScope = scope === definition.scope
      ? []
      : [['data-scope', scope]];
    const extras = [...exceptionalScope, ...additionalAttributes];
    const extraCell = extras.length === 0
      ? '<span aria-label="None">—</span>'
      : extras.map(([name, value]) => `<code>${escapeHtml(name)}="${escapeHtml(value)}"</code>`).join('<br>');

    return `<tr>
  <td><code class="component-part-token">${escapeHtml(part)}</code></td>
  <td><code>[data-part="${escapeHtml(part)}"]</code></td>
  <td>${escapeHtml(contract.purpose[korean ? 'ko' : 'en'])}</td>
  <td>${extraCell}</td>
</tr>`;
  }).join('\n');
  const heading = korean ? '## 파트' : '## Parts';
  const introduction = korean
    ? `공통 범위: <code class="component-scope-token">[data-scope="${escapeHtml(definition.scope)}"]</code>. 컴포넌트 내부로 스타일을 제한할 때 파트 선택자와 함께 사용합니다.`
    : `Shared scope: <code class="component-scope-token">[data-scope="${escapeHtml(definition.scope)}"]</code>. Combine it with a part selector to keep styles local to this component.`;
  const headings = korean
    ? ['파트', '선택자', '역할', '추가 속성']
    : ['Part', 'Selector', 'Role', 'Extra attributes'];
  return `${heading}\n\n${introduction}\n\n<div class="component-parts-table">\n<table>\n<thead>\n<tr>${headings.map((label) => `<th scope="col">${label}</th>`).join('')}</tr>\n</thead>\n<tbody>\n${rows}\n</tbody>\n</table>\n</div>`;
}

function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function keyboardSection(component, korean = false) {
  const contract = component.id === 'window-splitter'
    ? [
        { keys: 'Arrow Left / Arrow Right', behavior: 'Make the leading pane one step smaller or larger in a horizontal layout.', behaviorKo: '좌우 배치에서 앞쪽 영역을 한 단계 줄이거나 늘립니다.' },
        { keys: 'Arrow Up / Arrow Down', behavior: 'Make the leading pane one step smaller or larger in a vertical layout.', behaviorKo: '상하 배치에서 앞쪽 영역을 한 단계 줄이거나 늘립니다.' },
        { keys: 'Home / End', behavior: 'Move the separator to its minimum or maximum boundary.', behaviorKo: '구분선을 허용된 최소 또는 최대 경계로 이동합니다.' },
        { keys: 'Page Up / Page Down', behavior: 'Resize by the configured page step.', behaviorKo: '설정된 큰 단계만큼 영역 크기를 바꿉니다.' },
      ]
    : keyboardContract(component.id);
  const rows = contract
    .map((entry) => `| <kbd>${entry.keys.replaceAll(' / ', '</kbd> / <kbd>')}</kbd> | ${korean ? entry.behaviorKo : entry.behavior} |`)
    .join('\n');
  const heading = korean ? '## 키보드 동작' : '## Keyboard interaction';
  const tableHead = korean ? '| 키 | 동작 |\n| --- | --- |' : '| Key | Behavior |\n| --- | --- |';
  return `${heading}\n\n${tableHead}\n${rows}`;
}

function accessibilitySection(component, korean = false) {
  const contract = accessibilityContract(component.id);
  const heading = korean ? '## 접근성' : '## Accessibility';
  const summary = korean ? contract.korean : contract.english;
  if (!component.standard.startsWith('https://')) return `${heading}\n\n${summary}`;
  const link = korean
    ? `[관련 WAI-ARIA 패턴](${component.standard})에서 호스트 접근성 규칙을 확인할 수 있습니다.`
    : `See the [corresponding WAI-ARIA pattern](${component.standard}) for the host accessibility contract.`;
  return `${heading}\n\n${summary}\n\n${link}`;
}

function publicVueApi(component) {
  const source = vueSources[component];
  assert.equal(typeof source, 'string', `Missing @sectile/vue source module: ${component}`);
  const values = [...source.matchAll(/^export\s+(?:const|function|class)\s+(\w+)/gmu)].map((match) => match[1]);
  const types = [...source.matchAll(/^export\s+(?:interface|type)\s+(\w+)/gmu)].map((match) => match[1]);
  for (const match of source.matchAll(/^export\s+(type\s+)?\{([\s\S]*?)\}(?:\s+from\s+[^;]+)?;/gmu)) {
    const blockTypeOnly = match[1] !== undefined;
    for (const raw of match[2].split(',').map((value) => value.trim()).filter(Boolean)) {
      const entryTypeOnly = blockTypeOnly || raw.startsWith('type ');
      const normalized = raw.replace(/^type\s+/u, '');
      const exported = normalized.split(/\s+as\s+/u).at(-1);
      assert.ok(exported, `Invalid @sectile/vue export: ${component}/${raw}`);
      (entryTypeOnly ? types : values).push(exported);
    }
  }
  const uniqueValues = [...new Set(values)];
  const uniqueTypes = [...new Set(types)];
  assert.ok(uniqueValues.length > 0, `${component} requires a public Vue value export`);
  assert.ok(uniqueTypes.length > 0, `${component} requires a public Vue type export`);
  return { values: uniqueValues, types: uniqueTypes };
}

function title(value) {
  return value.split('-').map((part) => `${part[0].toUpperCase()}${part.slice(1)}`).join(' ');
}

function sentence(value) {
  const result = value.replaceAll('-', ' ');
  return `${result[0].toUpperCase()}${result.slice(1)}`;
}

function description(component) {
  const exact = componentSummaries[component.id];
  assert.equal(typeof exact, 'string', `Missing English component summary: ${component.id}`);
  return exact;
}

