import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import catalog from '../data/components.json' with { type: 'json' };

const root = resolve(import.meta.dirname, '..');
const check = process.argv.includes('--check');
const generated = catalog.components.filter((component) => component.id !== 'checkbox');

for (const component of generated) {
  const path = resolve(root, 'components', `${component.id}.md`);
  const expected = page(component);
  if (check) {
    const actual = await readFile(path, 'utf8');
    assert.equal(actual, expected, `${component.id}.md is stale; run pnpm generate`);
  } else {
    await writeFile(path, expected);
  }
}

console.log(JSON.stringify({ status: check ? 'current' : 'generated', pages: generated.length }, null, 2));

function page(component) {
  const name = title(component.id);
  const coreImport = `@sectile/core/${component.id}`;
  const domImport = `@sectile/dom/${component.id}`;
  const terminalImport = `@sectile/terminal/${component.id}`;
  const vueImport = `@sectile/vue/${component.id}`;
  const capabilities = component.capabilities.map((value) => `- ${sentence(value)}.`).join('\n');
  const standard = component.standard.startsWith('docs/')
    ? `/${component.standard.slice('docs/'.length).replace(/\.md(?=#|$)/u, '')}`
    : component.standard;
  const scenarios = [...new Set([...component.scenarios.dom, ...component.scenarios.terminal])]
    .map((value) => `- ${sentence(value)}.`)
    .join('\n');
  return `<!-- Generated by scripts/generate-component-pages.mjs. -->
# ${name}

${description(component.family, name)}

## Capabilities

${capabilities}

## Package availability

| Package | Import | Status |
| --- | --- | --- |
| Core | \`@sectile/core/${component.id}\` | Published |
| DOM | \`@sectile/dom/${component.id}\` | Published |
| Terminal | \`@sectile/terminal/${component.id}\` | Published |
| Vue | \`@sectile/vue/${component.id}\` | Workspace preview |

## Usage

Import the public component subpath for the host you are building. Namespace imports keep the available state, events, controllers, and projection helpers together while the API is explored.

::: code-group

\`\`\`ts [Core]
import * as ${identifier(name)} from '${coreImport}'
\`\`\`

\`\`\`ts [DOM]
import * as ${identifier(name)} from '${domImport}'
\`\`\`

\`\`\`ts [Terminal]
import * as ${identifier(name)} from '${terminalImport}'
\`\`\`

\`\`\`ts [Vue]
import * as ${identifier(name)} from '${vueImport}'
\`\`\`

:::

## Supported scenarios

${scenarios}

DOM and terminal scenarios refine the same semantic state. Host packages may expose different input and rendering helpers while preserving accepted transitions and controlled ownership.

## Interaction states

Component state that changes user-owned data supports controlled or uncontrolled ownership where listed above. Host projections distinguish disabled interaction from readonly inspection when the underlying control permits both.

## Semantics

The component contract follows [${standard.startsWith('http') ? 'the relevant accessibility pattern' : 'Sectile theory'}](${standard}). Visual styling remains outside the package; use host attributes, parts, and state projections as styling hooks.
`;
}

function title(value) {
  return value.split('-').map((part) => `${part[0].toUpperCase()}${part.slice(1)}`).join(' ');
}

function identifier(value) {
  const camel = value.replace(/\s+(.)/gu, (_match, letter) => letter.toUpperCase());
  return `${camel[0].toLowerCase()}${camel.slice(1)}`;
}

function sentence(value) {
  const result = value.replaceAll('-', ' ');
  return `${result[0].toUpperCase()}${result.slice(1)}`;
}

function description(family, name) {
  const descriptions = {
    checked: `${name} models a persistent checked or pressed state with explicit ownership.`,
    editing: `${name} separates editable draft state from accepted application value.`,
    'linear-choice': `${name} composes ordered navigation, eligibility, and selection semantics.`,
    range: `${name} models quantized values and host-independent range movement.`,
    'date-time': `${name} combines timezone-free civil values with calendar navigation and popup state.`,
    collection: `${name} composes cursor, selection, and collection projection semantics.`,
    menu: `${name} models hierarchical command navigation, open paths, and invocation.`,
    popup: `${name} owns popup state and explicit focus or dismissal effects.`,
    expansion: `${name} models disclosure and expansion policy without rendering assumptions.`,
    navigation: `${name} preserves native navigation while coordinating compound panels and triggers.`,
    'paged-navigation': `${name} projects a large logical range into a compact navigation window.`,
    'linear-action': `${name} coordinates focus and invocation across an ordered action set.`,
    'tree-choice': `${name} projects hierarchical choices into progressive selection columns.`,
    feedback: `${name} coordinates queued feedback, announcements, timing, and dismissal.`,
  };
  return descriptions[family] ?? `${name} exposes renderer-neutral interaction semantics.`;
}
